class CoordAttMeanMax(nn.Module):
    def __init__(self, inp, oup, groups=32):
        super(CoordAttMeanMax, self).__init__()
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))

        mip = max(8, inp // groups)

        self.conv1 = nn.Conv2d(inp, mip, kernel_size=1, stride=1, padding=0)
        self.bn1 = nn.BatchNorm2d(mip)
        self.relu = nn.ReLU(inplace=True)
        self.conv2 = nn.Conv2d(mip, oup, kernel_size=1, stride=1, padding=0)

    def forward(self, x):
        identity = x
        n, c, h, w = x.size()

        # Coordinate average pooling
        x_h = self.pool_h(x)                     # Shape: [B, C, H, 1]
        x_w = self.pool_w(x).permute(0, 1, 3, 2) # Shape: [B, C, 1, W] → [B, C, W, 1]
        y = torch.cat([x_h, x_w], dim=2)         # Shape: [B, C, H+W, 1]

        # Shared MLP
        y = self.conv1(y)
        y = self.bn1(y)
        y = self.relu(y)

        # Split and permute back
        x_h, x_w = torch.split(y, [h, w], dim=2)
        x_w = x_w.permute(0, 1, 3, 2)  # [B, C, W, 1] → [B, C, 1, W]

        # Attention maps
        a_h = self.conv2(x_h).sigmoid()
        a_w = self.conv2(x_w).sigmoid()

        # Expand and apply attention
        out = identity * a_h.expand_as(identity) * a_w.expand_as(identity)
        return out

class DCAFE(nn.Module):
    def __init__(self, in_channels, out_channels):
        super(DCAFE, self).__init__()
        self.coord_att = CoordAttMeanMax(in_channels, out_channels)

    def forward(self, x):
        return self.coord_att(x)

